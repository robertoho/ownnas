// npm install --prefix /tmp/ownnas-docx-test jsdom
// NODE_PATH is not used by ESM; override DOCX_TEST_DOM to use another install.
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const { JSDOM } = await import(pathToFileURL(process.env.DOCX_TEST_DOM || '/tmp/ownnas-docx-test/node_modules/jsdom/lib/api.js'));
const dom = new JSDOM('<div id="editor"></div>');
for (const key of ['window', 'document', 'DOMParser', 'XMLSerializer', 'Event']) globalThis[key] = key === 'window' ? dom.window : dom.window[key];
const { zipSync, unzipSync, strToU8, strFromU8 } = await import('../web/vendor/three/addons/libs/fflate.module.js');
const { openDocx, mountDocxEditor } = await import('../web/docx-editor.js');
const W = 'http://schemas.openxmlformats.org/wordprocessingml/2006/main';
const documentXml = `<w:document xmlns:w="${W}"><w:body><w:p><w:r><w:rPr><w:i/></w:rPr><w:t>Original</w:t></w:r></w:p><w:tbl><w:tr><w:tc><w:p><w:r><w:t>Cell</w:t></w:r></w:p></w:tc></w:tr></w:tbl><w:p><w:fldSimple w:instr="DATE"><w:r><w:t>Field</w:t></w:r></w:fldSimple></w:p><w:sectPr/></w:body></w:document>`;
const parts = { '[Content_Types].xml': strToU8('<Types/>'), 'word/document.xml': strToU8(documentXml), 'word/media/image.png': new Uint8Array([1,2,3]), 'word/header1.xml': strToU8('<header>Keep</header>') };
const bytes = zipSync(parts);
assert.throws(() => openDocx(new Uint8Array([1,2,3])));
assert.throws(() => openDocx(zipSync({ ...parts, '_xmlsignatures/sig1.xml': strToU8('<signature/>') })), /signed/);
const container = document.getElementById('editor');
let saved, changed = false;
const editor = mountDocxEditor(container, bytes, { onChange: dirty => changed = dirty, onSave: async data => { saved = data; } });
assert.equal(container.querySelectorAll('table td').length, 1);
assert.equal(container.querySelectorAll('[contenteditable="true"]').length, 2, 'field must be locked');
let text = container.querySelector('[contenteditable="true"]'); text.focus(); text.textContent = '<script>safe</script> & changed'; text.dispatchEvent(new Event('input'));
assert.equal(changed, true);
const button = label => [...container.querySelectorAll('button')].find(b => b.textContent === label);
button('Bold').click();
button('Add paragraph').click();
assert.equal(document.activeElement.getAttribute('contenteditable'), 'true');
await editor.save();
assert.equal(editor.dirty, false); assert.equal(changed, false);
const out = unzipSync(saved);
assert.deepEqual(out['word/media/image.png'], parts['word/media/image.png']);
assert.deepEqual(out['word/header1.xml'], parts['word/header1.xml']);
const xml = new DOMParser().parseFromString(strFromU8(out['word/document.xml']), 'application/xml');
assert.equal(xml.getElementsByTagNameNS(W, 't')[0].textContent, '<script>safe</script> & changed');
assert.equal(xml.getElementsByTagNameNS(W, 'b').length, 1);
assert.equal(xml.getElementsByTagNameNS(W, 'fldSimple').length, 1);
assert.equal(xml.getElementsByTagNameNS(W, 'p').length, 4);
editor.destroy(); assert.equal(container.children.length, 0);
const readonly = mountDocxEditor(container, bytes, { readonly: true });
assert.equal(container.querySelectorAll('[contenteditable="true"]').length, 0);
assert.equal(container.querySelectorAll('button').length, 0); readonly.destroy();
const failed = mountDocxEditor(container, bytes, { onSave: async () => { throw new Error('Conflict'); } });
text = container.querySelector('[contenteditable="true"]'); text.textContent = 'Unsaved'; text.dispatchEvent(new Event('input'));
await failed.save(); assert.equal(failed.dirty, true); assert.match(container.textContent, /Save failed: Conflict/);
assert.equal(container.querySelector('[contenteditable="true"]').textContent, 'Unsaved');
failed.destroy();
console.log('DOCX round-trip, preservation, editing, read-only, and failed-save tests passed.');

// Formatting values, undo/redo through a save, and Enter splitting a safe paragraph.
const rich = mountDocxEditor(container, bytes, { onSave: async () => {} });
const xmlOut = () => new DOMParser().parseFromString(strFromU8(unzipSync(rich.export())['word/document.xml']), 'application/xml');
const val = name => xmlOut().getElementsByTagNameNS(W, name)[0]?.getAttributeNS(W, 'val');
text = container.querySelector('[contenteditable="true"]'); text.focus();
button('Bold').click(); assert.equal(val('b'), '1', 'first toggle enables bold');
rich.undo(); assert.equal(val('b'), undefined); assert.equal(rich.dirty, false);
rich.redo(); assert.equal(val('b'), '1');
let select = container.querySelector('[aria-label="Font size"]'); select.value = '24'; select.dispatchEvent(new Event('change'));
assert.equal(val('sz'), '48'); assert.equal(container.querySelector('.docx-run').style.fontSize, '24pt');
let color = container.querySelector('[aria-label="Text color"]'); color.value = '#aabbcc'; color.dispatchEvent(new Event('change'));
assert.equal(val('color'), 'AABBCC');
button('Align center').click(); assert.equal(val('jc'), 'center');
select = container.querySelector('[aria-label="Paragraph style"]'); select.value = '2'; select.dispatchEvent(new Event('change'));
assert.equal(val('outlineLvl'), '1'); assert.equal(val('sz'), '36');
rich.undo(); assert.equal(val('outlineLvl'), undefined); assert.equal(val('sz'), '48');
rich.redo(); await rich.save(); assert.equal(rich.dirty, false);
rich.undo(); assert.equal(rich.dirty, true); rich.redo(); assert.equal(rich.dirty, false);
rich.destroy();
const split = mountDocxEditor(container, bytes);
text = container.querySelector('[contenteditable="true"]'); text.focus();
let range = document.createRange(); range.setStart(text.firstChild, 4); range.collapse(true);
window.getSelection().removeAllRanges(); window.getSelection().addRange(range);
text.dispatchEvent(new dom.window.InputEvent('beforeinput', { inputType: 'insertParagraph', bubbles: true, cancelable: true }));
const splitXml = new DOMParser().parseFromString(strFromU8(unzipSync(split.export())['word/document.xml']), 'application/xml');
const splitTexts = [...splitXml.getElementsByTagNameNS(W, 't')].map(n => n.textContent);
assert.deepEqual(splitTexts.slice(0, 2), ['Orig', 'inal']);
assert.equal(splitXml.getElementsByTagNameNS(W, 'i').length, 2, 'split preserves run formatting');
assert.equal(document.activeElement.textContent, 'inal');
split.undo(); assert.equal(container.querySelector('.docx-run').textContent, 'Original');
split.destroy();
console.log('DOCX formatting, undo/redo, saved-state tracking, and paragraph splitting tests passed.');
