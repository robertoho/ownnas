import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
import { pathToFileURL } from 'node:url';
const { JSDOM } = await import(pathToFileURL(process.env.DOCX_TEST_DOM || '/tmp/ownnas-docx-test/node_modules/jsdom/lib/api.js'));
const dom = new JSDOM(await fs.readFile('web/index.html', 'utf8'), { runScripts: 'outside-only' });
const ctx = dom.getInternalVMContext(), source = await fs.readFile('web/app.js', 'utf8');
const writes = [], loads = [], messages = [];
ctx.$ = id => dom.window.document.getElementById(id);
ctx.esc = str => String(str).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;');
ctx.api = async (url, options) => options ? (writes.push(options.json), {ok:true}) : null;
ctx.load = async (path, opts) => loads.push({path, opts}); ctx.toast = msg => messages.push(msg);
vm.runInContext('var state = {path:"Projects"};', ctx);
vm.runInContext(source.slice(source.indexOf('function typeIcon('), source.indexOf('function sortedEntries(')), ctx);
vm.runInContext(source.slice(source.indexOf('function inTrashPath('), source.indexOf('function renderFiles(')), ctx);
const folder = { path:'Projects', name:'Projects', dir:true, kind:'folder' };
assert.ok(ctx.entryIcon({...folder, folderAppearance:{color:'#abcdef',icon:'star'}}).includes('color:#abcdef'));
assert.ok(!ctx.entryIcon({...folder, folderAppearance:{color:'red;bad',icon:'__proto__'}}).includes('style='));
assert.equal(ctx.customizableFolder({...folder, path:'.ownnas-trash/Projects'}), false);
assert.equal(ctx.customizableFolder({...folder, kind:'archive-folder'}), false);
const dialog = ctx.$('folder-appearance-dialog'); dialog.showModal = () => { dialog.open = true; };
function close(value) { dialog.returnValue = value; dialog.open = false; dialog.dispatchEvent(new dom.window.Event('close')); }
let pending = ctx.customizeFolders([folder]); await new Promise(resolve => setTimeout(resolve, 0));
assert.equal(dialog.open, true);
assert.equal(dialog.querySelectorAll('[data-folder-icon]').length, 11);
dialog.querySelector('[data-folder-icon="star"]').click(); dialog.querySelector('[data-folder-color="#a855f7"]').click();
assert.equal(dialog.querySelector('[data-folder-icon="star"]').getAttribute('aria-pressed'), 'true');
assert.ok(ctx.$('folder-appearance-preview').innerHTML.includes('color:#a855f7'));
close('save'); await pending;
assert.equal(writes[0].icon, 'star'); assert.equal(writes[0].color, '#a855f7'); assert.deepEqual(Array.from(writes[0].paths), ['Projects']);
assert.equal(loads[0].opts.keepPreview, true);
pending = ctx.customizeFolders([folder]); await new Promise(resolve => setTimeout(resolve, 0)); close('cancel'); await pending; assert.equal(writes.length, 1);
pending = ctx.customizeFolders([folder, {...folder,path:'Other',name:'Other'}]); await new Promise(resolve => setTimeout(resolve, 0));
ctx.$('folder-appearance-reset').click(); close('save'); await pending;
assert.equal(writes[1].color, ''); assert.equal(writes[1].icon, 'folder'); assert.equal(writes[1].paths.length, 2);
console.log('Folder icons, color validation, dialog save/cancel/reset, and bulk customization tests passed.');
