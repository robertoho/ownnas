// NODE_PATH is not used by ESM; override ODT_TEST_DOM to use another jsdom install.
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { Buffer } from 'node:buffer';
const { JSDOM } = await import(pathToFileURL(process.env.ODT_TEST_DOM || '/tmp/ownnas-docx-test/node_modules/jsdom/lib/api.js'));
const dom = new JSDOM('<div id="editor"></div>');
for (const key of ['window', 'document', 'DOMParser', 'XMLSerializer', 'Event', 'Node']) globalThis[key] = key === 'window' ? dom.window : dom.window[key];
const { zipSync, unzipSync, strToU8, strFromU8 } = await import('../web/vendor/three/addons/libs/fflate.module.js');
const { openOdt, mountOdtEditor } = await import('../web/odt-editor.js');
const office = 'urn:oasis:names:tc:opendocument:xmlns:office:1.0';
const textNs = 'urn:oasis:names:tc:opendocument:xmlns:text:1.0';
const styleNs = 'urn:oasis:names:tc:opendocument:xmlns:style:1.0';
const fo = 'urn:oasis:names:tc:opendocument:xmlns:xsl-fo-compatible:1.0';
const content = `<office:document-content xmlns:office="${office}" xmlns:text="${textNs}" xmlns:style="${styleNs}" xmlns:fo="${fo}" office:version="1.3"><office:automatic-styles/><office:body><office:text><text:p><text:span text:style-name="Emphasis">Original</text:span></text:p><table:table xmlns:table="urn:oasis:names:tc:opendocument:xmlns:table:1.0"><table:table-row><table:table-cell><text:p><text:span>Cell</text:span></text:p></table:table-cell></table:table-row></table:table></office:text></office:body></office:document-content>`;
const styles = `<office:document-styles xmlns:office="${office}" xmlns:style="${styleNs}" xmlns:fo="${fo}"><office:styles><style:style style:name="Emphasis" style:family="text"><style:text-properties fo:font-style="italic"/></style:style></office:styles></office:document-styles>`;
const bytes = zipSync({ mimetype: { data: strToU8('application/vnd.oasis.opendocument.text'), level: 0 }, 'content.xml': strToU8(content), 'styles.xml': strToU8(styles), 'Pictures/image.png': new Uint8Array([1,2,3]) });
assert.throws(() => openOdt(new Uint8Array([1,2,3])));
const signedParts = { mimetype: { data: unzipSync(bytes).mimetype, level: 0 } };
for (const [name, data] of Object.entries(unzipSync(bytes))) if (name !== 'mimetype') signedParts[name] = data;
signedParts['META-INF/documentsignatures.xml'] = strToU8('<signature/>');
assert.throws(() => openOdt(zipSync(signedParts)), /signed/);
const container = document.getElementById('editor'); let saved, changed = false;
const editor = mountOdtEditor(container, bytes, { onChange: dirty => changed = dirty, onSave: async data => { saved = data; } });
assert.equal(container.querySelectorAll('table td').length, 1);
assert.equal(container.querySelectorAll('[contenteditable="true"]').length, 2);
let text = container.querySelector('[contenteditable="true"]'); assert.equal(text.style.fontStyle, 'italic');
text.focus(); text.textContent = '<script>safe</script> & changed'; text.dispatchEvent(new Event('input'));
const button = label => [...container.querySelectorAll('button')].find(b => b.textContent === label);
button('Bold').click(); assert.equal(changed, true);
await editor.save(); assert.equal(editor.dirty, false);
const outBytes = saved; const out = unzipSync(outBytes);
assert.deepEqual(out['Pictures/image.png'], new Uint8Array([1,2,3]));
assert.deepEqual(out.mimetype, strToU8('application/vnd.oasis.opendocument.text'));
const archive = Buffer.from(outBytes);
assert.equal(archive.readUInt16LE(8), 0, 'first mimetype member is stored, not compressed');
const xml = new DOMParser().parseFromString(strFromU8(out['content.xml']), 'application/xml');
assert.ok(xml.getElementsByTagNameNS(textNs, 'span').length >= 3);
assert.equal(xml.getElementsByTagNameNS(styleNs, 'style').length, 1);
assert.equal(xml.getElementsByTagNameNS(styleNs, 'text-properties')[0].getAttributeNS(fo, 'font-weight'), 'bold');
assert.equal(xml.getElementsByTagNameNS(textNs, 'span')[0].textContent, '<script>safe</script> & changed');
editor.undo(); assert.equal(editor.dirty, true); editor.redo(); assert.equal(editor.dirty, false);
editor.destroy();
const readonly = mountOdtEditor(container, bytes, { readonly: true });
assert.equal(container.querySelectorAll('[contenteditable="true"]').length, 0);
assert.equal(container.querySelectorAll('button').length, 0); readonly.destroy();
const blank = zipSync({ mimetype: { data: strToU8('application/vnd.oasis.opendocument.text'), level: 0 }, 'content.xml': strToU8(`<office:document-content xmlns:office="${office}" xmlns:text="${textNs}"><office:body><office:text><text:p/></office:text></office:body></office:document-content>`), 'META-INF/manifest.xml': strToU8('<manifest/>') });
const emptyEditor = mountOdtEditor(container, blank);
assert.equal(container.querySelectorAll('[contenteditable="true"]').length, 1, 'empty document starts editable');
button('Add paragraph').click();
assert.equal(container.querySelectorAll('.odt-page p').length, 2);
emptyEditor.destroy();
console.log('ODT package preservation, editing, stored mimetype, read-only, and undo/redo tests passed.');
